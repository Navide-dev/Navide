/** Shell interpreters that run an inline command string passed with `-c`
 * (including combined short flags such as `-lc`). Their command argument is
 * parsed recursively so the interpreter cannot hide the real executable. */
const SHELL_INTERPRETER_WRAPPERS: readonly string[] = ['sh', 'bash', 'zsh', 'dash']

/** Wrappers that forward their trailing arguments to another executable. */
const ARGUMENT_FORWARDING_WRAPPERS: readonly string[] = [
  'env',
  'sudo',
  'nice',
  'nohup',
  'xargs',
  'command',
  'time',
  'doas',
]

/** Wrappers can nest (`sudo env sh -c ...`); cap the recursion so a crafted
 * command cannot drive unbounded work in the authorization path. */
const MAX_SHELL_WRAPPER_DEPTH = 8

function isShellWrapperToken(token: string): boolean {
  const canonical = token.toLowerCase()
  return SHELL_INTERPRETER_WRAPPERS.includes(canonical) || ARGUMENT_FORWARDING_WRAPPERS.includes(canonical)
}

/** Reject executable tokens the Host cannot resolve lexically. */
function resolvableExecutableToken(token: string): boolean {
  if (!token) return false
  // A leading assignment changes the environment of the command that
  // follows it. Version 1 does not resolve shell prefixes, so do not let a
  // denylist inspect the assignment token and miss the real executable.
  if (/^[A-Za-z_][A-Za-z0-9_]*=/u.test(token)) return false
  // A path-qualified token is not reduced to a basename: doing so would let
  // a Plugin replace an allowlisted command with an arbitrary same-named
  // executable from the workspace or a temporary directory.
  if (token.includes('/') || token.includes('\\')) return false
  // A token built by parameter expansion is only known at execution time.
  if (token.includes('$')) return false
  return true
}

/** Split one already-segmented command into its whitespace-separated tokens,
 * removing quoting exactly as the first-token scanner does. */
function shellSegmentTokens(segment: string): string[] | null {
  const tokens: string[] = []
  let token = ''
  let started = false
  let quote: 'single' | 'double' | null = null
  let escaped = false
  for (let index = 0; index < segment.length; index += 1) {
    const char = segment[index]
    if (escaped) {
      token += char
      escaped = false
      continue
    }
    if (char === '\\' && quote !== 'single') {
      escaped = true
      started = true
      continue
    }
    if (quote === 'single') {
      if (char === "'") quote = null
      else token += char
      continue
    }
    if (quote === 'double') {
      if (char === '"') quote = null
      else token += char
      continue
    }
    if (char === "'") {
      quote = 'single'
      started = true
      continue
    }
    if (char === '"') {
      quote = 'double'
      started = true
      continue
    }
    if (/\s/.test(char)) {
      if (started) {
        tokens.push(token)
        token = ''
        started = false
      }
      continue
    }
    token += char
    started = true
  }
  if (quote !== null || escaped) return null
  if (started) tokens.push(token)
  return tokens.length > 0 ? tokens : null
}

/** Return the inline command string a shell interpreter was given with `-c`,
 * or null when the interpreter runs something that is not statically known
 * (a script operand, standard input, or a missing argument). */
function inlineShellCommandArgument(tokens: readonly string[]): string | null {
  for (let index = 1; index < tokens.length; index += 1) {
    const token = tokens[index]
    // `--` ends option parsing; whatever follows is a script operand.
    if (token === '--') return null
    if (token.startsWith('--')) continue
    if (token.startsWith('-') && token.length > 1) {
      if (!token.includes('c')) continue
      return tokens[index + 1] ?? null
    }
    return null
  }
  return null
}

/** Return the argument slice a forwarding wrapper hands to the next
 * executable, or null when the wrapper's own options make that undecidable. */
function forwardedWrapperArguments(tokens: readonly string[]): readonly string[] | null {
  for (let index = 1; index < tokens.length; index += 1) {
    const token = tokens[index]
    if (/^[A-Za-z_][A-Za-z0-9_]*=/u.test(token)) continue
    // An option may or may not consume the token after it, so the forwarded
    // executable cannot be identified without emulating the wrapper.
    if (token.startsWith('-')) return null
    return tokens.slice(index)
  }
  return null
}

/** Resolve one segment's tokens to every executable it runs: the wrapper
 * itself plus, recursively, whatever the wrapper hands execution to. */
function resolveShellExecutableTokens(tokens: readonly string[], depth: number): string[] | null {
  if (depth > MAX_SHELL_WRAPPER_DEPTH) return null
  const token = tokens[0]
  if (token === undefined || !resolvableExecutableToken(token)) return null
  const canonical = token.toLowerCase()
  if (SHELL_INTERPRETER_WRAPPERS.includes(canonical)) {
    const inline = inlineShellCommandArgument(tokens)
    if (inline === null) return null
    const nested = shellExecutables(inline, depth + 1)
    return nested === null ? null : [token, ...nested]
  }
  if (ARGUMENT_FORWARDING_WRAPPERS.includes(canonical)) {
    const forwarded = forwardedWrapperArguments(tokens)
    if (forwarded === null) return null
    const nested = resolveShellExecutableTokens(forwarded, depth + 1)
    return nested === null ? null : [token, ...nested]
  }
  return [token]
}

/** Return every executable a shell pipeline/chain runs: the token at the start
 * of each segment plus, for wrappers such as `sh -c` or `env`, the executables
 * those wrappers go on to run.
 * This is intentionally a lexical check: the Host never executes or expands the
 * command while deciding whether it is allowlisted. A wrapper whose target
 * cannot be resolved lexically fails closed. */
export function shellTopLevelExecutables(command: string): string[] | null {
  return shellExecutables(command, 0)
}

function shellExecutables(command: string, depth: number): string[] | null {
  if (depth > MAX_SHELL_WRAPPER_DEPTH) return null
  if (command.trim().length === 0) return null
  const segments: string[] = []
  let segmentStart = 0
  let quote: 'single' | 'double' | null = null
  let escaped = false

  const pushSegment = (end: number): boolean => {
    const segment = command.slice(segmentStart, end).trim()
    if (!segment) return false
    segments.push(segment)
    return true
  }

  for (let index = 0; index < command.length; index += 1) {
    const char = command[index]
    if (escaped) {
      escaped = false
      continue
    }
    if (char === '\\' && quote !== 'single') {
      escaped = true
      continue
    }
    if (quote === 'single') {
      if (char === "'") quote = null
      continue
    }
    if (quote === 'double') {
      if (char === '`' || (char === '$' && command[index + 1] === '(')) return null
      if (char === '"') quote = null
      continue
    }
    if (
      char === '`' ||
      (char === '$' && command[index + 1] === '(') ||
      char === '<' ||
      char === '>' ||
      char === '(' ||
      char === ')' ||
      char === '{' ||
      char === '}' ||
      char === '!'
    ) {
      return null
    }
    if (char === "'") {
      quote = 'single'
      continue
    }
    if (char === '"') {
      quote = 'double'
      continue
    }
    if (char === '|' && command[index + 1] === '&') {
      if (!pushSegment(index)) return null
      index += 1
      segmentStart = index + 1
      continue
    }
    if (char === ';' || char === '|' || char === '&' || char === '\n' || char === '\r') {
      if (!pushSegment(index)) return null
      if ((char === '|' || char === '&') && command[index + 1] === char) index += 1
      segmentStart = index + 1
    }
  }
  if (quote !== null || escaped || !pushSegment(command.length)) return null

  const executables: string[] = []
  for (const segment of segments) {
    let index = 0
    while (/\s/.test(segment[index] ?? '')) index += 1
    if (index === segment.length) return null
    let token = ''
    let tokenQuote: 'single' | 'double' | null = null
    let tokenEscaped = false
    for (; index < segment.length; index += 1) {
      const char = segment[index]
      if (tokenEscaped) {
        token += char
        tokenEscaped = false
        continue
      }
      if (char === '\\' && tokenQuote !== 'single') {
        tokenEscaped = true
        continue
      }
      if (tokenQuote === 'single') {
        if (char === "'") tokenQuote = null
        else token += char
        continue
      }
      if (tokenQuote === 'double') {
        if (char === '"') tokenQuote = null
        else token += char
        continue
      }
      if (char === "'") {
        tokenQuote = 'single'
        continue
      }
      if (char === '"') {
        tokenQuote = 'double'
        continue
      }
      if (/\s/.test(char)) break
      token += char
    }
    if (!token || tokenQuote !== null || tokenEscaped) return null
    if (!resolvableExecutableToken(token)) return null
    if (!isShellWrapperToken(token)) {
      executables.push(token.trim())
      continue
    }
    // A wrapper hides the executable that actually runs, so the whole segment
    // has to be tokenized and followed through.
    const segmentTokens = shellSegmentTokens(segment)
    if (segmentTokens === null) return null
    const resolved = resolveShellExecutableTokens(segmentTokens, depth)
    if (resolved === null) return null
    executables.push(...resolved)
  }
  return executables.every((value) => value.length > 0) ? executables : null
}

function shellCommandAllowed(command: string, allowlist: readonly string[]): boolean {
  const executables = shellTopLevelExecutables(command)
  return executables !== null && executables.every((executable) => allowlist.includes(executable))
}

/** Decide the agent-only Execution Policy filter for one first-level public
 * namespace or shell command. Manifest, Grant, catalog, and runtime checks are
 * intentionally outside this function and remain mandatory for every caller. */
export function executionPolicyAllows(
  initiator: AuthenticatedInitiator | undefined,
  snapshot: ExecutionPolicySnapshot | undefined,
  namespace: PluginSystemNamespace | 'shell',
  command?: string,
): boolean {
  // Direct user work is governed by the existing Host checks, not by the
  // agent-oriented Execution Policy. An omitted initiator preserves legacy
  // direct-user behavior for callers that predate this seam.
  if (!initiator || initiator.kind !== 'agent') return true
  if (!snapshot || snapshot.state === 'corrupt') return false

  const { policy } = snapshot
  if (policy.mode === 'full') return true
  if (namespace === 'shell') {
    const executables = shellTopLevelExecutables(command ?? '')
    if (!executables) return false
    // Policy entries are persisted in lowercase; normalize command tokens at
    // the enforcement boundary so case-insensitive filesystems cannot bypass policy.
    const canonicalExecutables = executables.map((executable) => executable.toLowerCase())
    if (policy.mode === 'allowlist') {
      return canonicalExecutables.every((executable) => policy.shell.includes(executable))
    }
    // A denylist is allow-by-default over an open vocabulary of executable
    // names, while the Host resolves a command purely lexically. Any leading
    // token the Host does not know may itself be a wrapper that runs the denied
    // executable — `timeout 5 git push --force`, `setsid`, `busybox sh -c`,
    // `ksh -c`, `perl -e`, `python3 -c`, `npx` — and enumerating wrapper names
    // can only ever chase the ones already thought of. So absence from the
    // denylist is not a grant: a denylist is enforced over the Host's closed
    // vocabulary of resolvable executables, and every resolved token must be
    // one the Host knows *and* one the policy does not deny.
    return canonicalExecutables.every(
      (executable) =>
        HOST_SHELL_EXECUTABLE_ALLOWLIST.includes(executable) && !policy.shell.includes(executable),
    )
  }
  // `web` reaches every page and sign-in the plugin's browser partition holds,
  // and a denylist written before the namespace existed never mentions it. So
  // it is never allowed by omission: only full mode or an allowlist naming it.
  if (namespace === 'web') return policy.mode === 'allowlist' && policy.system.includes('web')
  // Message text: like `web`, a denylist written before the namespace existed
  // never mentions it, so an agent gets it only from an allowlist naming it.
  if (namespace === 'agentMessages') return policy.mode === 'allowlist' && policy.system.includes('agentMessages')
  return policy.mode === 'allowlist'
    ? policy.system.includes(namespace)
    : !policy.system.includes(namespace)
}

function requiresWorkspace(
  binding: AuthenticatedRuntimeBinding | null
): binding is AuthenticatedRuntimeBinding {
  return binding !== null && typeof binding.workspaceId === 'string' && binding.workspaceId.length > 0
}

function requiresAiCliBinding(
  binding: AuthenticatedRuntimeBinding | null
): binding is AuthenticatedRuntimeBinding {
  return (
    requiresWorkspace(binding) &&
    typeof binding.instanceId === 'string' &&
    binding.instanceId.length > 0 &&
    typeof binding.audience === 'string' &&
    binding.audience.length > 0
  )
}

/** Pure Issue 03 authorization seam. It returns a plan only; process, PTY,
 * backend, and Electron side effects belong to later Host adapters. */
export function planPublicCapabilityCall(
  call: CapabilityCall,
  policy: Extract<PluginCapabilityPolicy, { kind: 'manifest-v2' }>,
  context: HostCapabilityContext
): PublicCapabilityDecision {
  const address = `${call.ns}.${call.method}`
  const entry = publicCapabilityEntry(address)
  if (!entry || entry.kind !== 'method') {
    return publicDenied(call.reqId, 'METHOD_NOT_FOUND', `unknown public capability '${address}'`)
  }

  if (entry.storage === true) {
    // Storage is Host-granted and deliberately absent from Manifest v2's
    // `permissions.system` namespace array.
  } else if (entry.namespace === 'shell') {
    if (!policy.shell) return undeclaredDenied(call.reqId, 'shell access is not declared')
  } else if (!policy.system.includes(entry.namespace)) {
    return undeclaredDenied(call.reqId, `system namespace '${entry.namespace}' is not declared`)
  }

  if (entry.eligibility === 'firstParty' && !context.publisherEligible) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'publisher is not eligible for this capability')
  }

  if (entry.storage === true) {
    return planStoragePartition(call, context)
  }

  const binding = context.runtimeBinding
  if (!binding || binding.pluginId !== call.pluginId) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'authenticated runtime binding is missing')
  }
  if (entry.scope === 'workspace' && !requiresWorkspace(binding)) {
    return publicDenied(call.reqId, 'WORKSPACE_SCOPE_VIOLATION', 'workspace binding is required')
  }
  if (entry.namespace === 'aiCli' && !requiresAiCliBinding(binding)) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'AI CLI view binding is required')
  }

  const grant = context.userGrant
  if (!grant || grant.packageVersion !== binding.packageVersion) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'package-version grant is missing')
  }
  if (entry.namespace === 'shell') {
    if (grant.shell !== policy.shell) {
      return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'shell mode is not user-approved')
    }
    if (policy.shell === 'full' && grant.highRiskShellConfirmed !== true) {
      return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'full shell requires high-risk confirmation')
    }
  } else if (!grant.system.includes(entry.namespace)) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', `system namespace '${entry.namespace}' is not user-approved`)
  }

  const args = publicRequestArgs(call)
  if (!args || !entry.validateRequest?.(args)) {
    return publicDenied(call.reqId, 'INVALID_ARGUMENT', `invalid request for '${address}'`)
  }
  if (
    entry.address === 'aiCli.startSession' &&
    (!context.aiCliProfiles || !context.aiCliProfiles.includes(String(args.profileId)))
  ) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'AI CLI profile is not Host-allowlisted')
  }

  const initiator = context.initiator
  if (initiator !== undefined && !isAuthenticatedInitiator(initiator)) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'authenticated initiator is invalid')
  }
  if (
    !executionPolicyAllows(
      initiator,
      context.executionPolicy,
      entry.namespace,
      entry.namespace === 'shell' ? entry.shellCommand ?? String(args.command) : undefined,
    )
  ) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'agent execution policy denied the operation')
  }

  // A gesture-gated address is refused when the request carries no gesture the
  // Host observed. Authorization above still wins: an unauthorized caller must
  // not learn that a gesture would have changed the answer. Agent- and
  // backend-originated calls never carry one, so an unattended view cannot hand
  // an arbitrary URL to the OS browser.
  if (entry.requiresUserGesture === true && call.userGesture !== true) {
    return publicDenied(call.reqId, 'USER_CANCELLED', `'${address}' requires a user gesture`)
  }

  let session: AuthenticatedRuntimeBinding | undefined
  if (entry.address === 'aiCli.cancelStart') {
    const requestId = args.requestId
    const pending =
      typeof requestId === 'string' && context.pendingStartBindings
        ? context.pendingStartBindings.get(requestId)
        : undefined
    if (!pending || !sameBinding(pending, binding)) {
      return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'AI CLI start request ownership mismatch')
    }
  }
  if (entry.namespace === 'aiCli' && 'sessionId' in args) {
    const sessionId = args.sessionId
    if (typeof sessionId !== 'string' || !context.sessionBindings) {
      return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'AI CLI session is not Host-bound')
    }
    session = context.sessionBindings.get(sessionId)
    if (!session || !sameBinding(session, binding)) {
      return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'AI CLI session ownership mismatch')
    }
  }

  if (entry.namespace === 'shell' && policy.shell === 'allowlist') {
    if (!shellCommandAllowed(entry.shellCommand ?? String(args.command), HOST_SHELL_EXECUTABLE_ALLOWLIST)) {
      return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'shell executable is not Host-allowlisted')
    }
  }

  return {
    kind: 'allow',
    plan: {
      kind: 'public',
      address,
      scope: entry.scope,
      args,
      runtime: binding,
      ...(initiator ? { initiator } : {}),
      ...(initiator && context.executionPolicy
        ? { policyRevision: context.executionPolicy.revision }
        : {}),
      ...(policy.shell && entry.namespace === 'shell' ? { shellMode: policy.shell } : {}),
      ...(session ? { session } : {}),
    },
  }
}

/** Select the versioned storage snapshot whose package version matches the
 *  binding's. Only a snapshot bound to `packageVersion` may be selected; a
 *  binding whose package version matches no stored snapshot fails closed. */
function selectStorageSnapshot(
  pluginId: string,
  packageVersion: string,
  tier: StorageSnapshotTier | undefined,
  storageSnapshots: ReadonlyMap<StorageSnapshotTier, string> | undefined
): StorageSnapshotRef | null {
  if (!storageSnapshots || !tier) return null
  if (!['candidate', 'active', 'previous'].includes(tier)) return null
  for (const [candidateTier, version] of storageSnapshots) {
    if (
      !['candidate', 'active', 'previous'].includes(candidateTier) ||
      typeof version !== 'string' ||
      version.length === 0
    ) {
      return null
    }
  }
  if (storageSnapshots.get(tier) !== packageVersion) return null
  return { pluginId, tier, packageVersion }
}

/** Host-managed storage planning. A storage call selects only a partition
 *  class (plugin|workspace) and a key; the Host derives the partition identity
 *  from the authenticated runtime binding and selects the versioned snapshot
 *  whose package version matches the binding. The Plugin never supplies, and
 *  can never override, any partition identity. */
function planStoragePartition(
  call: CapabilityCall,
  context: HostCapabilityContext
): PublicCapabilityDecision {
  const address = `${call.ns}.${call.method}`
  const initiator = context.initiator
  if (initiator !== undefined && !isAuthenticatedInitiator(initiator)) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'authenticated initiator is invalid')
  }
  const grant = context.userGrant
  const binding = context.runtimeBinding

  if (!binding || binding.pluginId !== call.pluginId) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'authenticated runtime binding is missing')
  }

  if (
    !grant ||
    grant.packageVersion !== binding.packageVersion ||
    grant.storage !== true
  ) {
    return publicDenied(call.reqId, 'CAPABILITY_DENIED', 'storage grant is not user-approved')
  }

  const args = publicRequestArgs(call)
  // Storage accepts only { scope, key }. Any partition identity the Plugin
  // might try to supply (pluginId, workspaceId, packageVersion, path) is
  // rejected because storageRequestValidationError allows only those keys.
  if (!args) {
    return publicDenied(call.reqId, 'INVALID_ARGUMENT', `invalid request for '${address}'`)
  }
  const requestError = storageRequestValidationError(
    args,
    address as 'storage.get' | 'storage.set' | 'storage.delete'
  )
  if (requestError) {
    return publicDenied(call.reqId, requestError, `invalid request for '${address}'`)
  }

  const partitionClass = args.scope as StoragePartitionClass
  const key = args.key as string

  if (partitionClass !== 'plugin' && !requiresWorkspace(binding)) {
    return publicDenied(call.reqId, 'WORKSPACE_SCOPE_VIOLATION', 'workspace binding is required')
  }

  const partition: StoragePartition =
    partitionClass === 'plugin'
      ? { pluginId: binding.pluginId, workspaceId: null, key }
      : { pluginId: binding.pluginId, workspaceId: binding.workspaceId ?? null, key }

  const snapshot = selectStorageSnapshot(
    binding.pluginId,
    binding.packageVersion,
    context.storageSnapshotTier,
    context.storageSnapshots
  )
  if (!snapshot) {
    return publicDenied(
      call.reqId,
      'CAPABILITY_DENIED',
      'no storage snapshot matches this package version'
    )
  }

  return {
    kind: 'allow',
    plan: {
      kind: 'public',
      address,
      scope: partitionClass,
      args,
      runtime: binding,
      storage: { partition, snapshot },
      ...(initiator ? { initiator } : {}),
    },
  }
}

/** Route a cataloged event only to the Host-authenticated package audience. */
export function isPublicCapabilityEventAllowed(
  policy: Extract<PluginCapabilityPolicy, { kind: 'manifest-v2' }>,
  event: string,
  payload: unknown,
  context: HostCapabilityContext,
  targetPluginId: string,
  sourceBinding?: AuthenticatedRuntimeBinding
): boolean {
  const entry = publicCapabilityEntry(event)
  if (!entry || entry.kind !== 'event') return false
  if (entry.namespace === 'shell' ? !policy.shell : !policy.system.includes(entry.namespace as PluginSystemNamespace)) return false
  if (entry.eligibility === 'firstParty' && !context.publisherEligible) return false
  const binding = context.runtimeBinding
  if (!binding || !requiresWorkspace(binding)) return false
  const grant = context.userGrant
  if (
    !grant ||
    grant.packageVersion !== binding.packageVersion ||
    (entry.namespace === 'shell' ? grant.shell !== policy.shell : !grant.system.includes(entry.namespace as PluginSystemNamespace))
  ) {
    return false
  }
  if (typeof targetPluginId !== 'string' || targetPluginId.length === 0) return false
  if (targetPluginId !== binding.pluginId) return false
  if (event === 'workspace.filesChanged') {
    if (
      !sourceBinding ||
      sourceBinding.pluginId !== HOST_EVENT_SOURCE_PLUGIN_ID ||
      !requiresWorkspace(sourceBinding) ||
      sourceBinding.packageVersion.length === 0 ||
      sourceBinding.instanceId !== null ||
      sourceBinding.audience !== null ||
      sourceBinding.workspaceId !== binding.workspaceId ||
      sourceBinding.packageVersion !== binding.packageVersion
    ) {
      return false
    }
    return (
      isRecord(payload) &&
      Object.keys(payload).every((key) => key === 'changes') &&
      Array.isArray(payload.changes) &&
      payload.changes.every(
        (change) =>
          isRecord(change) &&
          Object.keys(change).every((key) => key === 'path' || key === 'kind') &&
          typeof change.path === 'string' &&
          ['created', 'changed', 'deleted'].includes(String(change.kind))
      )
    )
  }
  if (event === 'ui.keybindingsChanged') {
    return Boolean(sourceBinding && sameBinding(sourceBinding, binding) && isRecord(payload) &&
      Object.keys(payload).every(key => key === 'content') && typeof payload.content === 'string')
  }
  if (event === 'shell.gitCredentialRequested' || event === 'shell.gitCredentialCancelled') {
    if (!sourceBinding || !sameBinding(sourceBinding, binding) || !isRecord(payload) ||
      typeof payload.requestId !== 'string' || !payload.requestId) return false
    return event === 'shell.gitCredentialCancelled'
      ? Object.keys(payload).every(key => key === 'requestId')
      : Object.keys(payload).every(key => ['requestId', 'host', 'prompt'].includes(key)) &&
        typeof payload.host === 'string' && typeof payload.prompt === 'string'
  }
  if (event === 'ui.editorPreferencesChanged') {
    return Boolean(sourceBinding && sameBinding(sourceBinding, binding) && validateEditorPreferencesEvent(payload))
  }
  if (event === 'ui.pluginStorageChanged') {
    return Boolean(sourceBinding && sameBinding(sourceBinding, binding) && isRecord(payload) &&
      Object.keys(payload).every(key => ['scope', 'key', 'value', 'deleted'].includes(key)) &&
      (payload.scope === 'plugin' || payload.scope === 'workspace') &&
      typeof payload.key === 'string' && payload.key.length > 0 && typeof payload.deleted === 'boolean' &&
      isPreferenceJsonValue(payload.value))
  }
  if (event === 'web.changed') {
    return Boolean(sourceBinding && sameBinding(sourceBinding, binding) && validateWebChangedEvent(payload))
  }
  if ((EDITOR_AI_EVENTS as readonly string[]).includes(event)) {
    return Boolean(sourceBinding && sameBinding(sourceBinding, binding) &&
      requiresAiCliBinding(binding) && validateEditorAiEvent(event, payload))
  }
  if (event !== 'aiCli.output' && event !== 'aiCli.exited') return false
  if (!sourceBinding || !sameBinding(sourceBinding, binding)) return false
  if (!requiresAiCliBinding(binding) || !isRecord(payload)) return false
  if (!context.sessionBindings) return false
  if (event === 'aiCli.output') {
    return (
      Object.keys(payload).every((key) => key === 'sessionId' || key === 'data') &&
      typeof payload.data === 'string' &&
      typeof payload.sessionId === 'string' &&
      context.sessionBindings.get(payload.sessionId) !== undefined &&
      sameBinding(context.sessionBindings.get(payload.sessionId)!, binding)
    )
  }
  if (
    Object.keys(payload).some((key) => key !== 'sessionId' && key !== 'exitCode') ||
    typeof payload.sessionId !== 'string' ||
    !Object.prototype.hasOwnProperty.call(payload, 'exitCode') ||
    (payload.exitCode !== null &&
      !(typeof payload.exitCode === 'number' && Number.isInteger(payload.exitCode)))
  ) {
    return false
  }
  const sessionId = payload.sessionId
  if (typeof sessionId !== 'string' || !context.sessionBindings) return false
  const session = context.sessionBindings.get(sessionId)
  return session !== undefined && sameBinding(session, binding)
}

/**
 * A decision about how to service a capability call. `respond` carries a
 * ready-made envelope (deny / built-in ping / unknown); `backend` names the
 * backend WS message type the manager should dispatch and await; `host` names
 * a main-process action from {@link HOST_CAPABILITIES}.
 */
export type CapabilityPlan =
  | { kind: 'respond'; response: CapabilityResponse }
  | { kind: 'backend'; wsType: string }
  | { kind: 'host'; action: string }
  | PublicCapabilityExecutionPlan

/**
 * M2 dispatch planner. Enforces scoping first (an un-granted namespace is
 * denied here and never reaches the backend), then routes:
 *   - `ping`            → in-process success (M1 built-in)
 *   - mapped `(ns,m)`   → `backend` with the WS type from {@link resolveWsType}
 *   - anything else     → `UNKNOWN`
 */
export function planCapabilityCall(
  call: CapabilityCall,
  policy: CapabilityPolicyInput,
  authorization?: HostCapabilityContext
): CapabilityPlan {
  if (isManifestV2Policy(policy)) {
    if (!authorization) {
      return {
        kind: 'respond',
        response: undispatched(buildError(call.reqId, 'CAPABILITY_DENIED', 'Host authorization context is missing')),
      }
    }
    const decision = planPublicCapabilityCall(call, policy, authorization)
    return decision.kind === 'allow'
      ? decision.plan
      : { kind: 'respond', response: undispatched(decision.response) }
  }
  if (!isCallAllowed(policy, call.ns, call.method)) {
    const label =
      isRequirementsArray(policy) || isLegacyPolicy(policy)
        ? call.ns
        : `${call.ns}.${call.method}`
    return {
      kind: 'respond',
      response: undispatched(undeclared(buildError(
        call.reqId,
        'CAP_DENIED',
        `capability '${label}' not granted`
      ))),
    }
  }
  if (call.ns === 'ping') {
    return { kind: 'respond', response: buildSuccess(call.reqId, { pong: true, echo: call.args }) }
  }
  const hostAction = HOST_CAPABILITIES[`${call.ns}.${call.method}`]
  if (hostAction) {
    return { kind: 'host', action: hostAction }
  }
  const wsType = resolveWsType(call.ns, call.method)
  if (!wsType) {
    return {
      kind: 'respond',
      response: undispatched(buildError(call.reqId, 'UNKNOWN', `no handler for '${call.ns}.${call.method}'`)),
    }
  }
  return { kind: 'backend', wsType }
}

/** Map a backend WS response envelope into the plugin-facing capability
 *  envelope, preserving the correlation id the plugin is awaiting. */
export function backendResponseToCapability(
  reqId: string,
  resp: WsResponse
): CapabilityResponse {
  if (resp.ok) return buildSuccess(reqId, resp.payload)
  const code = resp.error?.code === 'RESOURCE_LIMIT' ? 'RESOURCE_LIMIT' : 'BACKEND_ERROR'
  return buildError(reqId, code, resp.error?.message ?? 'backend request failed')
}

