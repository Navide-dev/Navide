/** A capability call as it arrives from a plugin view over IPC. */
export interface CapabilityCall {
  /** The manifest id of the calling plugin (injected by the manager, not the view). */
  pluginId: string
  /** Capability namespace, e.g. `ping`, `fs`, `git`. */
  ns: string
  /** Method within the namespace. */
  method: string
  /** Opaque, plugin-supplied arguments. */
  args: unknown
  /** Correlation id generated by the plugin preload. */
  reqId: string
  /** True when the Host preload observed a trusted user gesture in this view
   *  inside its activation window. Only Host preload code sets it: page script
   *  runs in an isolated world and cannot forge a trusted event. Entries marked
   *  `requiresUserGesture` in the catalog are refused without it. */
  userGesture?: boolean
}

/** The response envelope returned to the plugin view. */
export interface CapabilityResponse {
  reqId: string
  ok: boolean
  result?: unknown
  error?: { code: CapabilityErrorCode; message?: string }
}

