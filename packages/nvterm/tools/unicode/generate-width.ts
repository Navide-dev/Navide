// Usage: node --import ./packages/nvterm/tools/register.mjs packages/nvterm/tools/unicode/generate-width.ts <ucd-dir> <version>
// Reads EastAsianWidth.txt and DerivedGeneralCategory.txt from a Unicode
// Character Database release and writes src/widthTable.ts.
// Spec: UAX #11 (East Asian Width), Unicode chapter 4.5 (General Category).
//   width 0: General_Category Mn, Me, Cf (except the prepended concatenation
//            marks and U+00AD, which take a cell), Hangul Jamo medial vowels
//            and final consonants U+1160..U+11FF
//   width 2: East_Asian_Width W or F, including the unassigned code points
//            UAX #11 defaults to W (CJK ideograph blocks and planes 2-3)
//   width 1: everything else (East_Asian_Width A is treated as narrow)
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const [ucdDir, version] = process.argv.slice(2)
if (!ucdDir || !version) throw new Error('usage: generate-width.ts <ucd-dir> <version>')

type Range = [number, number]

function rangesWhere(file: string, keep: (value: string) => boolean): Range[] {
  const out: Range[] = []
  for (const raw of readFileSync(join(ucdDir!, file), 'utf8').split('\n')) {
    const line = raw.replace(/#.*/, '').trim()
    if (!line) continue
    const [codes, value] = line.split(';').map((s) => s.trim()) as [string, string]
    if (!keep(value)) continue
    const [a, b] = codes.split('..')
    out.push([parseInt(a!, 16), parseInt(b ?? a!, 16)])
  }
  return out
}

function merge(ranges: Range[]): Range[] {
  const sorted = [...ranges].sort((x, y) => x[0] - y[0])
  const out: Range[] = []
  for (const r of sorted) {
    const last = out[out.length - 1]
    if (last && r[0] <= last[1] + 1) last[1] = Math.max(last[1], r[1])
    else out.push([r[0], r[1]])
  }
  return out
}

function subtract(ranges: Range[], remove: Range[]): Range[] {
  const out: Range[] = []
  for (const [a, b] of ranges) {
    let pieces: Range[] = [[a, b]]
    for (const [c, d] of remove) {
      pieces = pieces.flatMap(([x, y]): Range[] => {
        if (d < x || c > y) return [[x, y]]
        const keep: Range[] = []
        if (c > x) keep.push([x, c - 1])
        if (d < y) keep.push([d + 1, y])
        return keep
      })
    }
    out.push(...pieces)
  }
  return merge(out)
}

const prependedMarks: Range[] = [[0x00ad, 0x00ad], [0x0600, 0x0605], [0x06dd, 0x06dd], [0x070f, 0x070f], [0x08e2, 0x08e2], [0x110bd, 0x110bd], [0x110cd, 0x110cd]]
const zero = subtract(merge([
  ...rangesWhere('DerivedGeneralCategory.txt', (gc) => gc === 'Mn' || gc === 'Me' || gc === 'Cf'),
  [0x1160, 0x11ff],
]), prependedMarks)

const defaultWide: Range[] = [[0x3400, 0x4dbf], [0x4e00, 0x9fff], [0xf900, 0xfaff], [0x20000, 0x2fffd], [0x30000, 0x3fffd]]
const wide = subtract(merge([...rangesWhere('EastAsianWidth.txt', (w) => w === 'W' || w === 'F'), ...defaultWide]), zero)

const format = (ranges: Range[]): string =>
  ranges.map(([a, b]) => `0x${a.toString(16)}, 0x${b.toString(16)}`).reduce<string[]>((lines, pair, i) => {
    if (i % 4 === 0) lines.push(`  ${pair},`)
    else lines[lines.length - 1] += ` ${pair},`
    return lines
  }, []).join('\n')

const out = `// Generated by tools/unicode/generate-width.ts from the Unicode ${version}
// Character Database (EastAsianWidth.txt, DerivedGeneralCategory.txt).
// Do not edit by hand. Pairs of inclusive [start, end] code point ranges.

export const UNICODE_VERSION = '${version}'

export const ZERO_WIDTH = new Uint32Array([
${format(zero)}
])

export const WIDE = new Uint32Array([
${format(wide)}
])
`
writeFileSync(new URL('../../src/widthTable.ts', import.meta.url), out)
console.log(`zero-width ranges: ${zero.length}, wide ranges: ${wide.length}`)
