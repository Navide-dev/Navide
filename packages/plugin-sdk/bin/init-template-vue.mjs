// `navide-plugin init --template vue`: a complete, buildable Manifest v2
// plugin — a Vue 3 view in a workbench region, a small native backend
// (Python, Backend Wire v1, one executable per platform through PyInstaller),
// one agent tool that calls it, a test suite, and a `check` script that runs
// `validate` and `scan` on the staged package. Everything the files do is
// explained in the generated README; the generator itself only spells them.

const PLUGIN_ID = /^[a-z0-9][a-z0-9-]*(\.[a-z0-9][a-z0-9-]*)+$/
// A tool name is `<prefix>_<name>`; the prefix is the id's last segment with
// hyphens removed and must be 2-16 lowercase letters or digits starting with a letter
// (shared/pluginAgentTools.ts AGENT_TOOL_NAME_PATTERN).
const TOOL_PREFIX = /^[a-z][a-z0-9]{1,15}$/
const MIN_NAVIDE = '>=0.2.39'

export function vueTemplateNames(id) {
  if (!PLUGIN_ID.test(id)) throw new Error(`plugin id '${id}' must be <namespace>.<name> in lowercase letters, digits and hyphens`)
  const segments = id.split('.')
  const slug = segments[segments.length - 1]
  const prefix = slug.replace(/-/g, '')
  if (!TOOL_PREFIX.test(prefix)) {
    throw new Error(
      `the vue template declares an agent tool, whose name prefix is the id's last segment without hyphens ('${prefix}'); ` +
      'it must be 2-16 lowercase letters or digits starting with a letter — pick such an id, or use the default template',
    )
  }
  return { publisher: segments[0], slug, prefix, executable: slug, method: `${prefix}.hello` }
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`

